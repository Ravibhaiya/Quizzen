package com.ravibhaiya.quizzen.domain

import kotlin.random.Random

/**
 * Selectable quiz modes for Vocabulary practice. At least one stays selected on the setup screen.
 */
enum class VocabularyQuizMode(val code: String) {
    Synonyms("syn"),
    Antonyms("ant"),
    ;

    companion object {
        val DEFAULT: Set<VocabularyQuizMode> = setOf(Synonyms, Antonyms)

        fun fromCode(code: String): VocabularyQuizMode? = entries.firstOrNull { it.code == code }

        fun encode(modes: Set<VocabularyQuizMode>): String =
            modes.sortedBy { it.ordinal }.joinToString("-") { it.code }

        fun decode(raw: String?): Set<VocabularyQuizMode> =
            raw.orEmpty()
                .split('-', ',')
                .mapNotNull { fromCode(it.trim()) }
                .toSet()
    }
}

/**
 * Configuration for a Vocabulary Study + Quiz session.
 */
data class VocabularyQuizConfig(
    val modes: Set<VocabularyQuizMode> = VocabularyQuizMode.DEFAULT,
    val wordCount: Int = VocabularyQuizRules.DEFAULT_WORDS,
    val questionCount: Int = VocabularyQuizRules.DEFAULT_QUESTIONS,
    val timerSeconds: Int = VocabularyQuizRules.DEFAULT_TIMER_SECONDS,
)

/**
 * A single 4-option multiple-choice Vocabulary question generated by [VocabularyQuizEngine].
 */
data class VocabularyQuizItem(
    val clusterId: String,
    val mode: VocabularyQuizMode,
    val promptWord: String,
    val correctAnswer: String,
    val options: List<String>,
    val promptDetails: WordDetails = WordDetails(word = promptWord),
    val optionDetails: List<WordDetails> = options.map { WordDetails(word = it) },
    val clusterWord: String = "",
    val clusterPartOfSpeech: String = "",
) {
    fun isCorrect(selectedOption: String): Boolean =
        selectedOption.trim().equals(correctAnswer.trim(), ignoreCase = true)

    fun detailsForOption(option: String): WordDetails =
        optionDetails.firstOrNull { it.word.trim().equals(option.trim(), ignoreCase = true) }
            ?: WordDetails(word = option)
}

/**
 * Pure-Kotlin rules and study-word selector for the Vocabulary quiz.
 */
object VocabularyQuizRules {
    const val MIN_WORDS = 1
    const val MAX_WORDS = 25
    const val DEFAULT_WORDS = 10
    const val MIN_QUESTIONS = 1
    const val MAX_QUESTIONS = 100
    const val DEFAULT_QUESTIONS = 25
    const val DEFAULT_TIMER_SECONDS = 15

    fun coerceWordCount(count: Int): Int = count.coerceIn(MIN_WORDS, MAX_WORDS)

    fun coerceQuestionCount(count: Int): Int = count.coerceIn(MIN_QUESTIONS, MAX_QUESTIONS)

    /** Normalized lowercase key used to persist and match locally saved mistake words. */
    fun mistakeKey(wordOrId: String): String = wordOrId.trim().lowercase()

    /**
     * Returns the canonical unique key(s) for [entry]: its Firestore [VocabularyEntry.id] when present,
     * otherwise its `word::partOfSpeech` identity key (so homographs like "Present" Noun vs Verb never collide).
     */
    fun entryMistakeKeys(entry: VocabularyEntry): Set<String> = buildSet {
        val id = mistakeKey(entry.id)
        if (id.isNotEmpty()) {
            add(id)
        } else {
            val identity = VocabularyRules.wordIdentityKey(entry.wordDetails)
            if (identity.isNotEmpty()) add(identity)
        }
    }

    /** Counts how many entries in [entries] share each normalized bare main word (to detect homographs). */
    fun bareWordCounts(entries: List<VocabularyEntry>): Map<String, Int> =
        entries.groupingBy { mistakeKey(it.wordDetails.word) }
            .eachCount()
            .filterKeys { it.isNotEmpty() }

    /**
     * True when [entry] matches [normalizedMistakes] (already lowercased).
     * Supports canonical ID/identity keys first, and falls back to legacy bare-word keys only when no other
     * entry shares the same bare spelling (preventing Noun/Verb homograph collisions).
     */
    fun matchesMistakeWords(
        entry: VocabularyEntry,
        normalizedMistakes: Set<String>,
        wordCountsByBareWord: Map<String, Int>,
    ): Boolean {
        if (normalizedMistakes.isEmpty()) return false
        if (entryMistakeKeys(entry).any { it in normalizedMistakes }) return true
        val bareWord = mistakeKey(entry.wordDetails.word)
        return bareWord.isNotEmpty() &&
            (wordCountsByBareWord[bareWord] ?: 0) <= 1 &&
            bareWord in normalizedMistakes
    }

    /**
     * Checks whether [entry] can generate at least one question under the selected [modes].
     */
    fun isEligible(entry: VocabularyEntry, modes: Set<VocabularyQuizMode>): Boolean {
        val clean = entry.sanitized()
        if (clean.wordDetails.word.isBlank()) return false
        val hasSynonyms = VocabularyQuizMode.Synonyms in modes && clean.synonyms.isNotEmpty()
        val hasAntonyms = VocabularyQuizMode.Antonyms in modes && clean.antonyms.isNotEmpty()
        return hasSynonyms || hasAntonyms
    }

    private fun entryIdentity(entry: VocabularyEntry): String =
        entry.id.trim().lowercase().ifEmpty { VocabularyRules.wordIdentityKey(entry.wordDetails) }

    /**
     * Picks up to [wordCount] distinct vocabulary entries from [entries] to study and be quizzed on:
     * - When [excludeEntries] is provided (for example when tapping the Shuffle button on the Study Words screen),
     *   excludes the currently shown entries first so new random word(s) are chosen whenever additional eligible words
     *   exist in the database (or reorders them when all eligible words are already shown).
     * - Otherwise selects randomly from eligible entries (prioritizing [mistakeWords] only when explicitly provided).
     *
     * Returns [emptyList] when [entries] has no eligible words for the selected [modes].
     */
    fun selectStudyWords(
        entries: List<VocabularyEntry>,
        modes: Set<VocabularyQuizMode>,
        wordCount: Int,
        random: Random = Random.Default,
        mistakeWords: Set<String> = emptySet(),
        excludeEntries: List<VocabularyEntry> = emptyList(),
    ): List<VocabularyEntry> {
        val targetCount = coerceWordCount(wordCount)
        val eligibleUser = entries
            .map { it.sanitized() }
            .filter { isEligible(it, modes) }
            .distinctBy(::entryIdentity)

        if (eligibleUser.isEmpty()) return emptyList()

        val excludedKeys = excludeEntries.map(::entryIdentity).toSet()
        if (excludedKeys.isNotEmpty() && eligibleUser.size > 1) {
            val freshPool = eligibleUser.filterNot { entryIdentity(it) in excludedKeys }.shuffled(random)
            if (freshPool.size >= targetCount) {
                return freshPool.take(targetCount)
            }
            val needed = targetCount - freshPool.size
            val fallbackPool = eligibleUser.filter { entryIdentity(it) in excludedKeys }.shuffled(random)
            val combined = (freshPool + fallbackPool.take(needed)).shuffled(random)
            val currentOrder = excludeEntries.map(::entryIdentity)
            if (combined.size > 1 && combined.map(::entryIdentity) == currentOrder) {
                return combined.drop(1) + combined.first()
            }
            return combined
        }

        val normalizedMistakes = mistakeWords.map(::mistakeKey).filter { it.isNotEmpty() }.toSet()
        if (normalizedMistakes.isEmpty()) {
            return eligibleUser.shuffled(random).take(targetCount)
        }

        val bareCounts = bareWordCounts(eligibleUser)
        val (savedPool, remainingPool) = eligibleUser.partition { entry ->
            matchesMistakeWords(entry, normalizedMistakes, bareCounts)
        }

        val chosenSaved = savedPool.shuffled(random).take(targetCount)
        if (chosenSaved.size >= targetCount) return chosenSaved

        val needed = targetCount - chosenSaved.size
        val chosenRemaining = remainingPool.shuffled(random).take(needed)
        return chosenSaved + chosenRemaining
    }

    /**
     * Built-in read-only vocabulary entries used as a last-resort distractor pool in [VocabularyQuizEngine] when a
     * small user database has fewer than 4 distinct words to build 4-option multiple-choice choices.
     * Never written to the database and never used to populate study words when the database is empty.
     */
    val FALLBACK_ENTRIES: List<VocabularyEntry>
        get() = VocabularyFallbackData.ENTRIES
}
