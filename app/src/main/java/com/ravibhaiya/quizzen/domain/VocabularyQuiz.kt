package com.ravibhaiya.quizzen.domain

import kotlin.random.Random

/**
 * Selectable quiz modes for Vocabulary practice. At least one stays selected on the setup screen.
 */
enum class VocabularyQuizMode(val code: String) {
    Synonyms("syn"),
    Antonyms("ant"),
    ;

    companion object {
        val DEFAULT: Set<VocabularyQuizMode> = setOf(Synonyms, Antonyms)

        fun fromCode(code: String): VocabularyQuizMode? = entries.firstOrNull { it.code == code }

        fun encode(modes: Set<VocabularyQuizMode>): String =
            modes.sortedBy { it.ordinal }.joinToString("-") { it.code }

        fun decode(raw: String?): Set<VocabularyQuizMode> =
            raw.orEmpty()
                .split('-', ',')
                .mapNotNull { fromCode(it.trim()) }
                .toSet()
    }
}

/**
 * Configuration for a Vocabulary Study + Quiz session.
 */
data class VocabularyQuizConfig(
    val modes: Set<VocabularyQuizMode> = VocabularyQuizMode.DEFAULT,
    val wordCount: Int = VocabularyQuizRules.DEFAULT_WORDS,
    val timerSeconds: Int = VocabularyQuizRules.DEFAULT_TIMER_SECONDS,
)

/**
 * A single 4-option multiple-choice Vocabulary question generated by [VocabularyQuizEngine].
 */
data class VocabularyQuizItem(
    val clusterId: String,
    val mode: VocabularyQuizMode,
    val promptWord: String,
    val correctAnswer: String,
    val options: List<String>,
    val promptDetails: WordDetails = WordDetails(word = promptWord),
    val optionDetails: List<WordDetails> = options.map { WordDetails(word = it) },
    val clusterWord: String = "",
) {
    fun isCorrect(selectedOption: String): Boolean =
        selectedOption.trim().equals(correctAnswer.trim(), ignoreCase = true)

    fun detailsForOption(option: String): WordDetails =
        optionDetails.firstOrNull { it.word.trim().equals(option.trim(), ignoreCase = true) }
            ?: WordDetails(word = option)
}

/**
 * Pure-Kotlin rules and study-word selector for the Vocabulary quiz.
 */
object VocabularyQuizRules {
    const val MIN_WORDS = 5
    const val MAX_WORDS = 25
    const val DEFAULT_WORDS = 10
    const val DEFAULT_TIMER_SECONDS = 15

    fun coerceWordCount(count: Int): Int = count.coerceIn(MIN_WORDS, MAX_WORDS)

    /** Normalized lowercase key used to persist and match locally saved mistake words. */
    fun mistakeKey(wordOrId: String): String = wordOrId.trim().lowercase()

    /** Returns the normalized keys for a [VocabularyEntry] (both its main word and its entry ID if non-blank). */
    fun entryMistakeKeys(entry: VocabularyEntry): Set<String> = buildSet {
        val word = mistakeKey(entry.wordDetails.word)
        if (word.isNotEmpty()) add(word)
        val id = mistakeKey(entry.id)
        if (id.isNotEmpty()) add(id)
    }

    /**
     * Checks whether [entry] can generate at least one question under the selected [modes].
     */
    fun isEligible(entry: VocabularyEntry, modes: Set<VocabularyQuizMode>): Boolean {
        val clean = entry.sanitized()
        if (clean.wordDetails.word.isBlank()) return false
        val hasSynonyms = VocabularyQuizMode.Synonyms in modes && clean.synonyms.isNotEmpty()
        val hasAntonyms = VocabularyQuizMode.Antonyms in modes && clean.antonyms.isNotEmpty()
        return hasSynonyms || hasAntonyms
    }

    /**
     * Picks up to [wordCount] distinct vocabulary entries to study and be quizzed on:
     * 1. First prioritizes eligible entries whose word/ID is in [mistakeWords] (saved from previous wrong answers or
     *    timeouts), shuffled so repeated practice stays fresh.
     * 2. Fills the remaining slots with random non-mistake eligible entries from [entries] (or [FALLBACK_ENTRIES] if
     *    fewer than [wordCount] user entries exist).
     */
    fun selectStudyWords(
        entries: List<VocabularyEntry>,
        modes: Set<VocabularyQuizMode>,
        wordCount: Int,
        random: Random = Random.Default,
        mistakeWords: Set<String> = emptySet(),
    ): List<VocabularyEntry> {
        val targetCount = coerceWordCount(wordCount)
        val normalizedMistakes = mistakeWords.map(::mistakeKey).filter { it.isNotEmpty() }.toSet()

        val eligibleUser = entries
            .map { it.sanitized() }
            .filter { isEligible(it, modes) }
            .distinctBy { it.wordDetails.word.lowercase() }

        val sourcePool = eligibleUser.ifEmpty {
            FALLBACK_ENTRIES.filter { isEligible(it, modes) }
        }
        if (normalizedMistakes.isEmpty()) {
            return sourcePool.shuffled(random).take(targetCount)
        }

        val (savedPool, remainingPool) = sourcePool.partition { entry ->
            entryMistakeKeys(entry).any { it in normalizedMistakes }
        }

        val chosenSaved = savedPool.shuffled(random).take(targetCount)
        if (chosenSaved.size >= targetCount) return chosenSaved

        val needed = targetCount - chosenSaved.size
        val chosenRemaining = remainingPool.shuffled(random).take(needed)
        return chosenSaved + chosenRemaining
    }

    /**
     * Built-in starter vocabulary entries (25 rich words with multiple synonyms, antonyms, English & Hinglish meanings,
     * and example sentences) so the Vocabulary quiz works out of the box even before the user's own words exist.
     * Read-only: these are never written to the database.
     */
    val FALLBACK_ENTRIES: List<VocabularyEntry>
        get() = VocabularyFallbackData.ENTRIES
}
